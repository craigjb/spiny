package spiny.platform

import spinal.core._
import spinal.lib.blackbox.xilinx.s7.IOBUFDS
import spinal.lib.io.TriState

package object xilinx {
  implicit class IOBUFDSRich(val factory: IOBUFDS.type) extends AnyVal {
    /** Buffers a tri-state onto a differential pad pair */
    def on(triState: TriState[Bool], p: Bool, n: Bool): IOBUFDS = {
      val buffer = IOBUFDS()
      buffer.I := triState.write
      buffer.T := !triState.writeEnable
      triState.read := buffer.O
      p := buffer.IO
      n := buffer.IOB
      buffer
    }
  }
}
